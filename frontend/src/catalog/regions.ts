/**
 * The types of a federal state: the norm types plus its own, a name of its own replacing the
 * norm's, and without the norm names it does not use.
 */
function stateTypes(id: string): RegionalType[] {
    const own = STATE_ROWS[id] ?? []
    const ownNames = new Set([...own.map(([name]) => name), ...(HIDDEN_NORM_NAMES[id] ?? [])])
    const norm = NORM_ROWS.filter(([name]) => !ownNames.has(name))
    return types(`de-${id.toLowerCase()}`, [...norm, ...own])
        .sort((left, right) => left.name.localeCompare(right.name, 'de'))
}

/** The region every new board starts in. */
export const DEFAULT_REGION = 'BE'

/** Berlin with the types of its fleet, then every other federal state. */
export const REGIONS: Region[] = [
    {id: 'BE', name: 'Berlin', types: BERLIN_TYPES},
    ...STATES.map(([id, name]) => ({id, name, types: stateTypes(id)})),
]

const BY_ID = new Map(REGIONS.map(region => [region.id, region]))

/** The region with an id, falling back to the default region. */
export function region(id: string): Region {
    return BY_ID.get(id) ?? BY_ID.get(DEFAULT_REGION)!
}
