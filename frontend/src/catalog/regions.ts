import type {BaseTypeId, Region, RegionalType} from './model'

/** A type as written below: short name, long name, base type and, where known, its call sign number. */
type TypeRow = [string, string, BaseTypeId, string?]

/** Builds the regional types of one region from rows, with ids prefixed by the region. */
function types(prefix: string, rows: TypeRow[]): RegionalType[] {
    return rows.map(([name, longName, base, radioCode]) => ({
        id: `${prefix}:${name}`, name, longName, base, ...(radioCode ? {radioCode} : {}),
    }))
}

