"""Generates the Berlin vehicle catalogue of the frontend from the fleet list of the Berlin fire brigade.

The list is a spreadsheet export with one row per vehicle (columns Wachtyp, Wache, Wachnummer,
Adresse, Herkunft, Typ, Funkname, Name, Bemerkung). It is not kept in the repository; the two
generated TypeScript modules are: the types, loaded with the app, and the fleet, loaded when a
vehicle is picked. Every vehicle type is assigned a base type, which decides the symbol shape, the
organisation colour and the default crew; a type no rule covers stops the script, so a new type in
a later list cannot slip in without one.

Usage: python tools/build_berlin_catalog.py <list.csv> [output directory]
"""

import csv
import json
import sys
from pathlib import Path

CATALOGUE = Path(__file__).resolve().parent.parent / "frontend" / "src" / "catalog"

BASE_RULES: list[tuple[str, str]] = [
    ("LHF-M", "engine-reduced"),
    ("LHF 10/5", "engine-squad"),
    ("LHF 1", "engine-group"),
    ("LHF 2", "engine-group"),
    ("LHF", "engine-squad"),
    ("LF", "engine-group"),
    ("TLF", "tanker"),
    ("DLK", "aerial"),
    ("TM", "aerial"),
    ("RW", "rescue"),
    ("ELW 2", "command-post"),
    ("ELW 1 Erkunder", "command-1"),
    ("ELW 1 LNA", "command-car-medical"),
    ("ELW 1 ", "command-car"),
    ("ELW 1", "command-1"),
    ("MTF", "transport"),
    ("SW", "hose"),
    ("GW SAN", "equipment-medical"),
    ("GW Mess", "cbrn-recon"),
    ("CBRN", "cbrn-recon"),
    ("GW", "equipment"),
    ("WLF", "swap-body-carrier"),
    ("AB", "roll-off-container"),
    ("FwA RTB", "boat-trailer"),
    ("FwA", "trailer"),
    ("LB", "boat"),
    ("MZB", "boat"),
    ("FwK", "crane"),
    ("LKW", "truck"),
    ("Radlader", "machine"),
    ("Teleskopstapler", "machine"),
    ("KLEF", "small-vehicle"),
    ("FRF", "first-responder"),
    ("STEMO", "stroke-unit"),
    ("ITW", "intensive-care"),
    ("NEF", "emergency-doctor"),
    ("RTW", "ambulance"),
]
"""Prefixes of the Berlin type names and the base type they map to; the first match wins."""

CREW_RULES: list[tuple[str, str | None]] = [
    ("LHF-M", None),
    ("LHF", "engine-squad"),
]
"""Prefixes of the Berlin type names whose crew differs from their base type's; the first match wins."""

STATION_KINDS = {"FW": "fire-station", "FF": "volunteer", "TD": "technical-service", "RW": "ambulance-station"}


def base_of(type_name: str) -> str:
    """Return the base type of a Berlin type name, or stop when no rule covers it."""
    for prefix, base in BASE_RULES:
        if type_name.startswith(prefix):
            return base
    raise SystemExit(f"No base type for vehicle type {type_name!r}; add a rule to BASE_RULES.")


def crew_of(type_name: str, base: str) -> str | None:
    """Return the base type whose crew a Berlin type starts with, when that differs from its own base."""
    for prefix, crew in CREW_RULES:
        if type_name.startswith(prefix):
            return crew if crew != base else None
    return None


PREFIX_NAMES = {"AB": "Abrollbehälter", "FwA": "Feuerwehranhänger", "LKW": "Lastkraftwagen", "GW": "Gerätewagen"}
"""Long forms of type name prefixes, for types the list gives no full name."""


def long_name(line: dict[str, str]) -> str:
    """Return the full name of a type. A name that runs on into the remark column, because the list
    splits it at a comma, is joined again; a type without a name gets its short name with the
    prefix written out, or the short name alone."""
    name, remark = line["Name"].strip(), line["Bemerkung"].strip()
    if not name:
        prefix, _, rest = line["Typ"].strip().partition(" ")
        return f"{PREFIX_NAMES[prefix]} {rest}".strip() if prefix in PREFIX_NAMES else line["Typ"].strip()
    return f"{name}, {remark}" if remark[:1].islower() else name


def type_id(type_name: str) -> str:
    """Return the catalogue id of a Berlin type."""
    return f"be:{type_name}"


HEADER = (
    "/**\n"
    " * Generated by tools/build_berlin_catalog.py from the fleet list of the Berlin fire brigade.\n"
    " * Do not edit by hand.\n"
    " */\n"
)


def _lines(items: list[dict]) -> str:
    """Return one JSON object per line, as the elements of a TypeScript array literal."""
    return "\n".join(f"    {json.dumps(item, ensure_ascii=False)}," for item in items)


def build_types(rows: list[dict[str, str]]) -> str:
    """Return the TypeScript module with every vehicle type of the given rows."""
    types: dict[str, dict] = {}
    for line in sorted(rows, key=lambda row: not row["Name"].strip()):
        name = line["Typ"].strip()
        entry = types.setdefault(name, {"id": type_id(name), "name": name, "longName": "", "base": base_of(name)})
        entry["longName"] = entry["longName"] or long_name(line)
        crew = crew_of(name, entry["base"])
        if crew:
            entry["crew"] = crew
    return (
        f"{HEADER}"
        "import type {RegionalType} from './model'\n"
        "\n"
        "/** Every vehicle type in service in Berlin. */\n"
        "export const BERLIN_TYPES: RegionalType[] = [\n"
        f"{_lines(sorted(types.values(), key=lambda item: item['name']))}\n"
        "]\n"
    )


def build_fleet(rows: list[dict[str, str]]) -> str:
    """Return the TypeScript module with every vehicle of the given rows."""
    fleet = [
        {
            "callsign": line["Funkname"].strip(),
            "type": type_id(line["Typ"].strip()),
            "station": line["Wache"].strip(),
            "stationNumber": line["Wachnummer"].strip(),
            "stationKind": STATION_KINDS.get(line["Wachtyp"].strip(), "other"),
            "external": line["Herkunft"].strip() == "Extern",
        }
        for line in rows
        if line["Funkname"].strip()
    ]
    fleet.sort(key=lambda vehicle: (vehicle["stationNumber"], vehicle["callsign"]))
    return (
        f"{HEADER}"
        "import type {FleetVehicle} from './model'\n"
        "\n"
        "/** Every vehicle of the Berlin fire brigade with its call sign and station. */\n"
        "export const BERLIN_FLEET: FleetVehicle[] = [\n"
        f"{_lines(fleet)}\n"
        "]\n"
    )


def main() -> None:
    """Read the list named on the command line and write both catalogue modules."""
    if len(sys.argv) < 2:
        raise SystemExit(__doc__)
    with open(sys.argv[1], encoding="utf-8", newline="") as source:
        rows = list(csv.DictReader(source))
    output = Path(sys.argv[2]) if len(sys.argv) > 2 else CATALOGUE
    (output / "berlin-types.generated.ts").write_text(build_types(rows), encoding="utf-8")
    (output / "berlin-fleet.generated.ts").write_text(build_fleet(rows), encoding="utf-8")
    print(f"{output}: {len({line['Typ'] for line in rows})} types, {len(rows)} vehicles")


if __name__ == "__main__":
    main()
